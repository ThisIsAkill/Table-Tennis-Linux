"""Generate project/src/button_prompt_art.inc from the PlayStation button artwork.

Usage (developers only; the build uses the committed .inc):
    python3 project/tools/make_button_art.py dist/assets/resource/flash/flash.rpf

For each Xbox button icon in the game's menus (A, B, X, Y, LB, RB: DXT5, tiled, no mipmaps),
the generated file holds:
  - a fingerprint (FNV-1a 64 of the icon's used DXT blocks as they lie in guest memory), read
    from the menu archive given on the command line, so the engine can recognise the icon when
    the game loads it. Only the hash is stored, nothing of the game's image;
  - the matching PlayStation icon from project/assets/button_prompts/*.png (this project's own
    artwork), compressed to DXT5 with ImageMagick and byte-swapped to the guest's 16-bit
    big-endian layout, one 16-byte block per entry in row-major block order.
The engine places the blocks with the same tiling as the original (button_prompts.cpp).
"""
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'project' / 'assets' / 'button_prompts'
OUT = ROOT / 'project' / 'src' / 'button_prompt_art.inc'
sys.path.insert(0, str(Path(__file__).parent))
import patch_menu  # noqa: E402

# Icon order matches tabletennis::prompts::Icon. Texture names in the main menu movie.
ICONS = [
    ('A', 'pongui_001_xen_0177', 'ps_cross.png', 64, 64),
    ('B', 'pongui_001_xen_0172', 'ps_circle.png', 64, 64),
    ('X', 'pongui_001_xen_0161', 'ps_square.png', 64, 64),
    ('Y', 'pongui_001_xen_0166', 'ps_triangle.png', 64, 64),
    ('LB', 'pongui_001_xen_0183', 'ps_l1.png', 64, 32),
    ('RB', 'pongui_001_xen_0188', 'ps_r1.png', 64, 32),
]
DXT5 = 0x14


def tiled_offset(x, y, pitch, log2_bpb):
    """texture_util::GetTiledOffset2D: byte offset of block x,y; pitch in blocks."""
    pitch = (pitch + 31) & ~31
    macro = ((x >> 5) + (y >> 5) * (pitch >> 5)) << (log2_bpb + 7)
    micro = ((x & 7) + ((y & 0xE) << 2)) << log2_bpb
    offset = macro + ((micro & ~0xF) << 1) + (micro & 0xF) + ((y & 1) << 4)
    return (((offset & ~0x1FF) << 3) + ((y & 16) << 7) + ((offset & 0x1C0) << 2) +
            (((((y & 8) >> 2) + (x >> 3)) & 3) << 6) + (offset & 0x3F))


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def xbox_fingerprints(rpf):
    archive, entries = patch_menu._read_archive(Path(rpf))
    movie, _, _ = patch_menu._read_movie(archive, entries, b'pongui_001.xeck')
    movie = bytes(movie)
    base = struct.unpack_from('>I', movie, 8)[0]
    result = []
    for _, texture, _, width, height in ICONS:
        name = movie.rindex(b't:/', 0, movie.index(texture.encode() + b'.dds'))
        record = movie.index(struct.pack('>I', base + name)) - 12
        header = struct.unpack_from('>I', movie, record + 16)[0] - base
        fetch = struct.unpack_from('>6I', movie, header + 0x10)
        if fetch[1] & 0x3F != DXT5 or not fetch[0] >> 31:
            raise ValueError(f'{texture}: not a tiled DXT5 texture')
        pitch_blocks = (((fetch[0] >> 22) & 0x1FF) << 5) // 4
        data = (fetch[1] & 0xFFFFF000) - base
        blocks = b''.join(
            movie[data + tiled_offset(bx, by, pitch_blocks, 4):][:16]
            for by in range(height // 4) for bx in range(width // 4))
        result.append(fnv1a64(blocks))
    return result


def playstation_blocks(png, width, height):
    with tempfile.TemporaryDirectory() as tmp:
        dds = Path(tmp) / 'icon.dds'
        subprocess.run(['magick', str(png), '-resize', f'{width}x{height}!', '-define', 'dds:compression=dxt5',
                        '-define', 'dds:mipmaps=0', '-define', 'dds:cluster-fit=true', str(dds)], check=True)
        raw = dds.read_bytes()
    if raw[:4] != b'DDS ' or raw[84:88] != b'DXT5':
        raise ValueError(f'{png}: ImageMagick did not write DXT5')
    blocks = raw[128:128 + (width // 4) * (height // 4) * 16]
    swapped = bytearray(blocks)
    swapped[0::2], swapped[1::2] = blocks[1::2], blocks[0::2]   # guest: 16-bit big-endian words
    return bytes(swapped)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    fingerprints = xbox_fingerprints(sys.argv[1])
    lines = ['// Generated by project/tools/make_button_art.py from project/assets/button_prompts. Do not edit.',
             '// Per icon: the Xbox icon fingerprint and the PlayStation icon as guest-format DXT5 blocks.', '']
    for (label, _, png, width, height), fingerprint in zip(ICONS, fingerprints):
        data = playstation_blocks(ART / png, width, height)
        lines.append(f'// {label} -> {png}')
        lines.append(f'constexpr uint64_t kXbox{label}Hash = 0x{fingerprint:016X}ULL;')
        lines.append(f'constexpr uint8_t kPlayStation{label}[{len(data)}] = {{')
        for i in range(0, len(data), 24):
            lines.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 24]) + ',')
        lines.append('};')
        lines.append('')
    OUT.write_text('\n'.join(lines))
    print(f'Wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
