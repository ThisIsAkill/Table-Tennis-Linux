"""Builds and checks the translations of the port's own text (see project/src/l10n.h).

  localization.py build   write project/src/localization_data.inc from project/localization/*.json
  localization.py check   fail when a T/F/N text in project/src has no row, a row has the wrong
                          number of {} values, or localization_data.inc is out of date
  localization.py missing print the texts without a row, as JSON rows to fill in

Rows are [en, fr, de, es, it]; an empty translation falls back to English.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "src"
TABLES = ROOT / "localization"
OUTPUT = SOURCES / "localization_data.inc"
LITERAL = r'"(?:[^"\\\n]|\\.)*"'
CALL = re.compile(r'(?<![A-Za-z0-9_])(?:l10n::)?([TFN])\(\s*((?:' + LITERAL + r'\s*)+)[,)]')
ESCAPES = {"n": b"\n", "t": b"\t", '"': b'"', "\\": b"\\", "'": b"'", "?": b"?"}


def decode(literals):
    """The text of adjacent C string literals."""
    out = bytearray()
    for lit in re.findall(LITERAL, literals):
        body, i = lit[1:-1], 0
        while i < len(body):
            ch = body[i]
            if ch != "\\":
                out += ch.encode()
                i += 1
                continue
            nxt = body[i + 1]
            if nxt == "x":
                j = i + 2
                while j < len(body) and body[j] in "0123456789abcdefABCDEF":
                    j += 1
                out.append(int(body[i + 2:j], 16))
                i = j
            else:
                out += ESCAPES.get(nxt, nxt.encode())
                i += 2
    return out.decode()


def used_texts():
    texts = {}
    for path in sorted(SOURCES.glob("*.cpp")) + sorted(SOURCES.glob("*.h")):
        if path.name in ("l10n.h", "l10n.cpp"):
            continue
        source = path.read_text(encoding="utf-8")
        for match in CALL.finditer(source):
            line = source.count("\n", 0, match.start()) + 1
            texts.setdefault(decode(match.group(2)), f"{path.name}:{line}")
    return texts


def load_rows():
    rows, seen = [], {}
    for table in sorted(TABLES.glob("*.json")):
        for row in json.loads(table.read_text(encoding="utf-8")):
            if not (isinstance(row, list) and len(row) == 5 and all(isinstance(t, str) for t in row)):
                sys.exit(f"{table.name}: a row must be five strings [en, fr, de, es, it]: {row!r}")
            if row[0] in seen:
                if seen[row[0]] != row:
                    sys.exit(f"{table.name}: '{row[0]}' is translated differently in another row")
                continue
            for text in row[1:]:
                if text and text.count("{}") != row[0].count("{}"):
                    sys.exit(f"{table.name}: '{text}' needs {row[0].count('{}')} {{}} like '{row[0]}'")
            seen[row[0]] = row
            rows.append(row)
    return rows


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render(rows):
    lines = ["// Generated by project/tools/localization.py from project/localization/*.json. Do not edit.\n"]
    for row in sorted(rows, key=lambda r: r[0]):
        lines.append("{{" + ", ".join(c_string(t) for t in row) + "}},\n")
    return "".join(lines)


def main():
    command = sys.argv[1] if len(sys.argv) > 1 else "check"
    rows = load_rows()
    if command == "build":
        OUTPUT.write_text(render(rows), encoding="utf-8")
        print(f"{OUTPUT.relative_to(ROOT.parent)}: {len(rows)} texts")
        return
    known = {row[0] for row in rows}
    missing = {text: where for text, where in used_texts().items() if text not in known}
    if command == "missing":
        print(json.dumps([[text, "", "", "", ""] for text in missing], ensure_ascii=False, indent=0))
        return
    problems = [f"{where}: no translation row for {text!r}" for text, where in missing.items()]
    incomplete = [row[0] for row in rows if not all(row[1:])]
    if incomplete:
        problems += [f"row without all four translations: {text!r}" for text in incomplete]
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != render(rows):
        problems.append("localization_data.inc is out of date: run project/tools/localization.py build")
    for problem in problems:
        print(problem)
    if problems:
        sys.exit(1)
    print(f"Translations complete: {len(rows)} texts.")


if __name__ == "__main__":
    main()
